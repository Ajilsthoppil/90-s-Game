export function getAllGames(): GameDefinition[] {
  return [...GAME_REGISTRY];
}

export function getAvailableGames(): GameDefinition[] {
  return GAME_REGISTRY.filter((game) => game.status === 'AVAILABLE');
}

export function getComingSoonGames(): GameDefinition[] {
  return GAME_REGISTRY.filter((game) => game.status === 'COMING_SOON');
}

export function getGameById(id: string): GameDefinition | undefined {
  return GAME_REGISTRY.find((game) => game.id === id);
}

export function isGameAvailable(id: string): boolean {
  const game = getGameById(id);
  return game?.status === 'AVAILABLE';
}
